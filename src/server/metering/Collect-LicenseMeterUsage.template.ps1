#Requires -Version 5.1
<#
LicenseMeter Windows usage collector, protocol 2.
Generated by LicenseMeter for one workspace: the program list below matches the
Windows apps that workspace deploys through Intune. Upload a newly generated
copy when LicenseMeter reports that the app list changed.
Deploy as an Intune Remediations DETECTION-only script, SYSTEM, 64-bit, hourly.
Enable Audit Process Creation (Success) separately through approved policy.
Does not configure auditing, contact a network endpoint, or collect user names,
command lines, paths or raw events. Writes only its own local checkpoint.
Output describes program starts, not foreground use, installation or licensing.
See https://docs.licensemeter.com/connectors/windows-metering/
#>
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
$CatalogId = 'LM_CATALOG_ID'
$Programs = @('LM_PROGRAMS')
$inv = [Globalization.CultureInfo]::InvariantCulture
function Format-Utc([DateTime]$Value) { $Value.ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ', $inv) }
function Read-Utc([string]$Value) { [DateTime]::Parse($Value, $inv, [Globalization.DateTimeStyles]::RoundtripKind).ToUniversalTime() }
function Hour-Key([DateTime]$Value) { $Value.ToUniversalTime().ToString('yyyyMMddHH', $inv) }

$now = [DateTime]::UtcNow
$watch = @{}
foreach ($program in $Programs) { if ($program) { $watch[$program.ToLowerInvariant()] = $true } }
# Per program: last start, when watching began, and starts per UTC hour (24 h).
$apps = @{}
$coverage = $now
$health = 'collector_error'
$mutex = $null
$held = $false

function Assert-NoReparsePoint([string]$Path) {
    if ((Test-Path -LiteralPath $Path) -and ((Get-Item -LiteralPath $Path -Force).Attributes -band [IO.FileAttributes]::ReparsePoint)) {
        throw 'Refusing a redirected state path.'
    }
}

try {
    $identity = [Security.Principal.WindowsIdentity]::GetCurrent()
    $principal = New-Object Security.Principal.WindowsPrincipal($identity)
    if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) { throw 'Administrator access required.' }
    $mutex = New-Object Threading.Mutex($false, 'Global\LicenseMeterUsage')
    # Intune can start an on-demand and a scheduled run together. Wait for the
    # other run instead of reporting an error that would replace its result.
    try { $held = $mutex.WaitOne(150000) } catch [Threading.AbandonedMutexException] { $held = $true }
    if (-not $held) { throw 'Collector already running.' }
    $now = [DateTime]::UtcNow
    $coverage = $now

    # Locale-independent audit policy check. No policy changes are made.
    if (-not ('LicenseMeterAuditPolicy' -as [type])) {
        Add-Type -TypeDefinition @'
using System;
using System.Runtime.InteropServices;
public static class LicenseMeterAuditPolicy {
    [StructLayout(LayoutKind.Sequential)]
    public struct Info { public Guid Subcategory; public uint Options; public Guid Category; }
    [DllImport("advapi32.dll", SetLastError=true)]
    [return: MarshalAs(UnmanagedType.U1)]
    public static extern bool AuditQuerySystemPolicy(ref Guid id, uint count, out IntPtr result);
    [DllImport("advapi32.dll")] public static extern void AuditFree(IntPtr buffer);
    public static bool CreationEnabled() {
        Guid id = new Guid("0CCE922B-69AE-11D9-BED3-505054503030");
        IntPtr result;
        if (!AuditQuerySystemPolicy(ref id, 1, out result)) throw new InvalidOperationException("Audit policy unavailable");
        try { return (((Info)Marshal.PtrToStructure(result, typeof(Info))).Options & 1) != 0; }
        finally { AuditFree(result); }
    }
}
'@
    }
    $root = Join-Path $env:ProgramData 'LicenseMeter'
    $folder = Join-Path $root 'Metering'
    foreach ($path in @($root, $folder)) {
        Assert-NoReparsePoint $path
        [void][IO.Directory]::CreateDirectory($path)
        $acl = New-Object Security.AccessControl.DirectorySecurity
        $acl.SetAccessRuleProtection($true, $false)
        foreach ($sid in @('S-1-5-18', 'S-1-5-32-544')) {
            $account = New-Object Security.Principal.SecurityIdentifier($sid)
            $rule = New-Object Security.AccessControl.FileSystemAccessRule($account, 'FullControl', 'ContainerInherit,ObjectInherit', 'None', 'Allow')
            $acl.AddAccessRule($rule)
        }
        Set-Acl -LiteralPath $path -AclObject $acl
    }
    # The protocol 1 checkpoint is never read again.
    $legacy = Join-Path $folder 'usage-v1.json'
    if (Test-Path -LiteralPath $legacy) { Remove-Item -LiteralPath $legacy -Force }
    $stateFile = Join-Path $folder 'usage-v2.json'
    Assert-NoReparsePoint $stateFile
    $health = 'ok'
    $previous = $null
    if (Test-Path -LiteralPath $stateFile) {
        try {
            if ((Get-Item -LiteralPath $stateFile).Length -gt 524288) { throw 'Oversize state' }
            $previous = Get-Content -LiteralPath $stateFile -Raw | ConvertFrom-Json
            if ($previous.version -ne 2 -or -not $previous.record -or [long]$previous.record -lt 1) { throw 'Invalid checkpoint' }
            $priorStart = Read-Utc $previous.start
            $priorEnd = Read-Utc $previous.end
            if ($priorStart -gt $priorEnd -or $priorEnd -gt $now) { throw 'Coverage gap' }
            $coverage = $priorStart
            if ($previous.apps) {
                foreach ($property in $previous.apps.PSObject.Properties) {
                    $exe = $property.Name.ToLowerInvariant()
                    # Programs removed from the list are forgotten.
                    if (-not $watch.ContainsKey($exe)) { continue }
                    $entry = @{ last = $null; since = (Read-Utc $property.Value.since); hours = @{} }
                    if ($property.Value.last) { $entry.last = Read-Utc $property.Value.last }
                    if ($entry.since -gt $now -or ($entry.last -and $entry.last -gt $now)) { throw 'Invalid entry' }
                    if ($property.Value.hours) {
                        foreach ($hour in $property.Value.hours.PSObject.Properties) { $entry.hours[$hour.Name] = [int]$hour.Value }
                    }
                    $apps[$exe] = $entry
                }
            }
        } catch {
            $previous = $null
            $apps = @{}
            $coverage = $now
            $health = 'log_gap'
        }
    }
    if (-not [LicenseMeterAuditPolicy]::CreationEnabled()) {
        $health = 'audit_disabled'
        $apps = @{}
        if (Test-Path -LiteralPath $stateFile) { Remove-Item -LiteralPath $stateFile -Force }
    } else {
        $newest = Get-WinEvent -LogName Security -MaxEvents 1
        # Capture the report time AFTER the upper bookmark. Otherwise starts
        # during initialization could be skipped while their bookmark advances.
        $now = [DateTime]::UtcNow
        if (-not $previous) { $coverage = $now }
        # Programs added to the list are watched from now on.
        foreach ($exe in $watch.Keys) {
            if (-not $apps.ContainsKey($exe)) { $apps[$exe] = @{ last = $null; since = $now; hours = @{} } }
        }
        $upper = [long]$newest.RecordId
        $lower = $upper # First run establishes coverage now, never backdates it.
        if ($previous) {
            $checkpoint = [long]$previous.record
            $boundary = @(Get-WinEvent -LogName Security -FilterXPath "*[System[EventRecordID=$checkpoint]]" -MaxEvents 1 -ErrorAction SilentlyContinue)
            if ($checkpoint -gt $upper -or $boundary.Count -ne 1 -or $boundary[0].TimeCreated.ToUniversalTime().Ticks.ToString() -ne $previous.recordTime) {
                $coverage = $now
                $health = 'log_reset'
            } else { $lower = $checkpoint }
        }
        if ($lower -lt $upper) {
            $xpath = "*[System[(EventID=4688 or EventID=4719) and EventRecordID > $lower and EventRecordID <= $upper]]"
            $query = New-Object Diagnostics.Eventing.Reader.EventLogQuery('Security', [Diagnostics.Eventing.Reader.PathType]::LogName, $xpath)
            $reader = New-Object Diagnostics.Eventing.Reader.EventLogReader($query)
            $processed = 0
            try {
                while ($null -ne ($event = $reader.ReadEvent())) {
                    try {
                        $processed++
                        if ($processed -gt 100000 -or ([DateTime]::UtcNow - $now).TotalSeconds -gt 90) {
                            # Advance the upper checkpoint with an explicit gap so a
                            # busy device can recover on its next scheduled run.
                            $coverage = $now; $health = 'log_gap'; break
                        }
                        [xml]$xml = $event.ToXml()
                        $fields = @{}
                        foreach ($field in $xml.Event.EventData.Data) { $fields[$field.Name] = [string]$field.'#text' }
                        if ($event.Id -eq 4719 -and $fields['SubcategoryGuid'] -eq '{0CCE922B-69AE-11D9-BED3-505054503030}') {
                            $coverage = $now
                            $health = 'log_gap'
                        }
                        if ($event.Id -eq 4688) {
                            $exe = [IO.Path]::GetFileName($fields['NewProcessName']).ToLowerInvariant()
                            if ($watch.ContainsKey($exe)) {
                                $started = $event.TimeCreated.ToUniversalTime()
                                if ($started -le $now) {
                                    $entry = $apps[$exe]
                                    if ($null -eq $entry.last -or $started -gt $entry.last) { $entry.last = $started }
                                    # A program that starts copies of itself counts once.
                                    $parent = [IO.Path]::GetFileName([string]$fields['ParentProcessName']).ToLowerInvariant()
                                    if ($parent -ne $exe) {
                                        $key = Hour-Key $started
                                        if ($entry.hours.ContainsKey($key)) { $entry.hours[$key]++ } else { $entry.hours[$key] = 1 }
                                    }
                                }
                            }
                        }
                    } finally { $event.Dispose() }
                }
            } finally { $reader.Dispose() }
            # Detect rollover during collection as well as between runs.
            $oldest = Get-WinEvent -LogName Security -Oldest -MaxEvents 1
            if ([long]$oldest.RecordId -gt ($lower + 1)) { $coverage = $now; $health = 'log_gap' }
        }
        # A coverage restart applies to every program; old starts stay known.
        $retention = $now.AddDays(-120)
        $firstHour = Hour-Key $now.AddHours(-23)
        $saved = @{}
        foreach ($exe in $apps.Keys) {
            $entry = $apps[$exe]
            if ($entry.since -lt $coverage) { $entry.since = $coverage }
            if ($entry.last -and $entry.last -lt $retention) { $entry.last = $null }
            $hours = @{}
            foreach ($key in $entry.hours.Keys) { if ($key -ge $firstHour) { $hours[$key] = $entry.hours[$key] } }
            $entry.hours = $hours
            $saved[$exe] = @{ last = $(if ($entry.last) { Format-Utc $entry.last } else { $null }); since = (Format-Utc $entry.since); hours = $hours }
        }
        $checkpointState = @{ version = 2; catalog = $CatalogId; start = (Format-Utc $coverage); end = (Format-Utc $now); record = $upper; recordTime = $newest.TimeCreated.ToUniversalTime().Ticks.ToString(); apps = $saved }
        $temp = Join-Path $folder ('usage-' + [Guid]::NewGuid().ToString() + '.tmp')
        try {
            [IO.File]::WriteAllText($temp, ($checkpointState | ConvertTo-Json -Depth 6 -Compress), (New-Object Text.UTF8Encoding($false)))
            Move-Item -LiteralPath $temp -Destination $stateFile -Force
        } finally { if (Test-Path -LiteralPath $temp) { Remove-Item -LiteralPath $temp -Force } }
    }
} catch {
    $health = 'collector_error'
    $coverage = $now
    $apps = @{}
    # No raw exception, event data or paths are ever returned to Intune.
} finally {
    if ($held) { $mutex.ReleaseMutex() }
    if ($null -ne $mutex) { $mutex.Dispose() }
}

# Only started programs are listed, most recent first: [program, minutes before
# the report end, starts in the last 24 hours]. Later watch starts go in "w".
$firstHour = Hour-Key $now.AddHours(-23)
$later = @{}
$rows = @(foreach ($exe in $apps.Keys) {
    $entry = $apps[$exe]
    if ($entry.since -gt $coverage) { $later[$exe] = Format-Utc $entry.since }
    if (-not $entry.last) { continue }
    $count = 0
    foreach ($key in $entry.hours.Keys) { if ($key -ge $firstHour) { $count += $entry.hours[$key] } }
    [pscustomobject]@{ x = $exe; m = [int][Math]::Floor(($now - $entry.last).TotalMinutes); n = [int]$count }
}) | Sort-Object m
$entries = New-Object Collections.ArrayList
foreach ($row in $rows) { [void]$entries.Add(@($row.x, $row.m, $row.n)) }
$truncated = $false
while ($true) {
    $report = [ordered]@{ v = 2; c = $CatalogId; s = (Format-Utc $coverage); e = (Format-Utc $now); h = $health; a = $entries }
    if ($later.Count) { $report.w = $later }
    if ($truncated) { $report.t = 1 }
    $output = $report | ConvertTo-Json -Depth 5 -Compress
    if ($output.Length -le 2048) { break }
    # Never emit cut-off JSON. Drop the oldest starts and say so.
    if ($entries.Count -gt 0) { $entries.RemoveAt($entries.Count - 1); $truncated = $true }
    elseif ($later.Count) { $later = @{}; $truncated = $true }
    else { $output = '{"v":2,"error":"output_too_large"}'; break }
}
Write-Output $output
exit 0
